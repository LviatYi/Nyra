param(
    [string]$VcpkgRoot = $env:VCPKG_ROOT,
    [string]$LibClangPath = $env:LIBCLANG_PATH
)

$ErrorActionPreference = 'Stop'
$projectRoot = Split-Path -Parent $PSScriptRoot
$cargoDirectory = Join-Path $projectRoot '.cargo'
$cargoConfig = Join-Path $cargoDirectory 'config.toml'
$generatedMarker = '# Generated by scripts/install-opencv-dev.ps1; do not edit.'
if (Test-Path -LiteralPath (Join-Path $cargoDirectory 'config')) {
    throw 'An existing .cargo/config takes precedence over config.toml. Configure OpenCV in it manually.'
}
if ((Test-Path -LiteralPath $cargoConfig) -and
    !(Get-Content -LiteralPath $cargoConfig -Raw).StartsWith($generatedMarker)) {
    throw 'Existing .cargo/config.toml was not generated by Nyra; configure OpenCV in it manually.'
}
if (!$VcpkgRoot) { throw 'Set VCPKG_ROOT to a bootstrapped vcpkg installation.' }
$vcpkg = Join-Path $VcpkgRoot 'vcpkg.exe'
$portFile = Join-Path $VcpkgRoot 'ports/opencv4/vcpkg.json'
if (!(Test-Path -LiteralPath $vcpkg) -or !(Test-Path -LiteralPath $portFile)) {
    throw 'VCPKG_ROOT must contain vcpkg.exe and the opencv4 port.'
}
$port = Get-Content -LiteralPath $portFile -Raw | ConvertFrom-Json
if ($port.version -ne '4.12.0' -or $port.'port-version' -ne 1) {
    throw 'Nyra requires the vcpkg opencv4 port version 4.12.0#1; use a vcpkg checkout with that port.'
}
if (!$LibClangPath) {
    $vswhere = Join-Path ${env:ProgramFiles(x86)} 'Microsoft Visual Studio/Installer/vswhere.exe'
    if (Test-Path -LiteralPath $vswhere) {
        $vs = & $vswhere -latest -property installationPath
        if ($vs) { $LibClangPath = Join-Path $vs 'VC/Tools/Llvm/x64/bin' }
    }
}
if (!$LibClangPath -or !(Test-Path -LiteralPath (Join-Path $LibClangPath 'libclang.dll')) -or
    !(Test-Path -LiteralPath (Join-Path $LibClangPath 'clang.exe'))) {
    throw 'Set LIBCLANG_PATH to the directory containing 64-bit libclang.dll and clang.exe.'
}
$cache = Join-Path $projectRoot 'target/opencv-dev'
$installed = Join-Path $cache 'installed'
& $vcpkg install 'opencv4[core]:x64-windows' "--x-install-root=$installed" "--x-buildtrees-root=$cache/buildtrees" "--x-packages-root=$cache/packages" "--downloads-root=$cache/downloads"
if ($LASTEXITCODE -ne 0) { throw 'OpenCV installation failed; see vcpkg output.' }
$triplet = Join-Path $installed 'x64-windows'
$include = Join-Path $triplet 'include/opencv4'
$lib = Join-Path $triplet 'lib'
$bin = Join-Path $triplet 'bin'
$core = @(Get-ChildItem -LiteralPath $lib -Filter 'opencv_core*.lib')
$imgproc = @(Get-ChildItem -LiteralPath $lib -Filter 'opencv_imgproc*.lib')
if ($core.Count -ne 1 -or $imgproc.Count -ne 1 -or !(Test-Path -LiteralPath (Join-Path $include 'opencv2/core/version.hpp'))) {
    throw 'OpenCV headers or import libraries are missing or ambiguous.'
}
$env:OPENCV_LINK_LIBS = "$($core[0].BaseName),$($imgproc[0].BaseName)"
$env:OPENCV_LINK_PATHS = $lib
$env:OPENCV_INCLUDE_PATHS = $include
$env:LIBCLANG_PATH = $LibClangPath
$env:CLANG_PATH = Join-Path $LibClangPath "clang.exe"
$env:PATH = "$LibClangPath;$bin;$env:PATH"

# Cargo reads this file for IDE builds too, even when the IDE was already open.
# JSON strings are also valid TOML basic strings, including escaped Windows paths.
$settings = @{
    OPENCV_LINK_LIBS = $env:OPENCV_LINK_LIBS
    OPENCV_LINK_PATHS = $env:OPENCV_LINK_PATHS
    OPENCV_INCLUDE_PATHS = $env:OPENCV_INCLUDE_PATHS
    LIBCLANG_PATH = $env:LIBCLANG_PATH
    CLANG_PATH = $env:CLANG_PATH
}
$lines = @($generatedMarker, '[env]')
foreach ($name in @('OPENCV_LINK_LIBS', 'OPENCV_LINK_PATHS', 'OPENCV_INCLUDE_PATHS', 'LIBCLANG_PATH', 'CLANG_PATH')) {
    $value = ConvertTo-Json -InputObject $settings[$name] -Compress
    $lines += "$name = { value = $value, force = true }"
}
New-Item -ItemType Directory -Path $cargoDirectory -Force | Out-Null
[IO.File]::WriteAllText($cargoConfig, (($lines -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))

# Cargo runs the debug executable from target/debug; make its DLLs discoverable
# without requiring an IDE process to inherit this script's PATH.
$debugDirectory = Join-Path $projectRoot 'target/debug'
New-Item -ItemType Directory -Path $debugDirectory -Force | Out-Null
foreach ($dll in Get-ChildItem -LiteralPath $bin -Filter '*.dll') {
    $destination = Join-Path $debugDirectory $dll.Name
    if (Test-Path -LiteralPath $destination) {
        $sourceHash = (Get-FileHash -LiteralPath $dll.FullName -Algorithm SHA256).Hash
        $destinationHash = (Get-FileHash -LiteralPath $destination -Algorithm SHA256).Hash
        if ($sourceHash -ne $destinationHash) { throw "Conflicting DLL in $destination; inspect it before replacing." }
    }
    Copy-Item -LiteralPath $dll.FullName -Destination $destination -Force
}
Write-Output "OpenCV development environment ready: $triplet"
Write-Output "Cargo environment written to $cargoConfig; debug DLLs copied to $debugDirectory."
